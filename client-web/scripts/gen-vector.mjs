// Emit the cross-implementation test vector: sign a FIXED request with a FIXED
// 32-byte seed and FIXED nonce/ts using the shipped signer, and print the JSON
// the Rust `auth` crate loads to prove the two implementations agree.
//
// Build first, then run with the sumo loader (which redirects the libsodium
// import to its working CJS build):
//   npm run build
//   node --import ./scripts/sumo-loader-register.mjs scripts/gen-vector.mjs
//
// The output is committed as auth/tests/vectors/web_pop.json. Regenerate it
// (and re-run `cargo test`) only if the canonical format or encodings change.

import { identityFromSeed, signRequest, httpCanonical, sha256Hex, sodiumReady } from '../dist/index.js';

// --- the fixed vector inputs ---
const SEED = Uint8Array.from({ length: 32 }, (_, i) => i);
const METHOD = 'POST';
const PATH = '/upsert';
const BODY = new TextEncoder().encode('{"hello":"plane"}');
const NONCE = 'Zml4ZWQtbm9uY2UtZm9yLXRoZS1jcm9zcy1pbXBsLXZlY3Rvcg=='; // fixed base64 string
const TS = 1_700_000_000_000;

const sodium = await sodiumReady();
const id = await identityFromSeed(SEED);
const headers = await signRequest(id, 'OPAQUE_BISCUIT', { method: METHOD, path: PATH, body: BODY }, {
  nonce: NONCE,
  ts: TS,
});
const bodyHash = sha256Hex(sodium, BODY);
const canonical = httpCanonical(METHOD, PATH, bodyHash, NONCE, TS);

const vector = {
  _comment:
    'Generated by client-web/scripts/gen-vector.mjs. The Rust auth crate uses this to prove the TS signer and the Rust PEP agree on the http/v0 canonical + Ed25519 PoP.',
  seed_hex: sodium.to_hex(SEED),
  method: METHOD,
  path: PATH,
  body_utf8: new TextDecoder().decode(BODY),
  body_sha256_hex: bodyHash,
  nonce: NONCE,
  ts_ms: TS,
  canonical,
  pubkey_hex: headers['x-dispatch-pubkey'],
  pop_b64: headers['x-dispatch-pop'],
};

process.stdout.write(JSON.stringify(vector, null, 2) + '\n');
